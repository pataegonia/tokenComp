#!/usr/bin/env bash
# Preserve tasks 0-5; tasks 6-8 add P0/P1/P2 at lambda .0256 with Full context.
select_spatial_predictor_condition() {
  local task="$1"
  case "${task}" in
    0|1|6) SCORE_SPATIAL_PREDICTOR=linear;    PREDICTOR_TAG=p0_linear ;;
    2|3|7) SCORE_SPATIAL_PREDICTOR=residual3; PREDICTOR_TAG=p1_residual3 ;;
    4|5|8) SCORE_SPATIAL_PREDICTOR=residual7; PREDICTOR_TAG=p2_residual7 ;;
    *) echo "ERROR: spatial-predictor grid expects task id 0 through 8" >&2; return 1 ;;
  esac

  RANK=56
  RATE_LAMBDA=0.0064
  GRID_TASK_ID=0
  SCORE_CHANNEL_CONTEXT=true
  PARENT_PRIOR_TAG=m1c1s1
  PARENT_TASK_ID=8
  if (( task >= 6 )); then
    RATE_LAMBDA=0.0256
    GRID_TASK_ID=2
    PARENT_TASK_ID=9
  elif (( task % 2 == 1 )); then
    RATE_LAMBDA=0.0256
    GRID_TASK_ID=2
    SCORE_CHANNEL_CONTEXT=false
    PARENT_PRIOR_TAG=m1c0s1
    PARENT_TASK_ID=7
  fi

  USE_RESIDUAL=true
  USE_MORTON=true
  TRANSFORM=nonlinear
  TRANSFORM_HIDDEN=32
  SCORE_MEAN_CONDITION=true
  SCORE_SPATIAL_CONTEXT=true
  SCORE_SPATIAL_HIDDEN="${SPATIAL_PREDICTOR_SPATIAL_HIDDEN:-32}"
  SCORE_SLICE_CHANNELS="${SPATIAL_PREDICTOR_SLICE_CHANNELS:-16}"
  SCORE_CONTEXT_HIDDEN="${SPATIAL_PREDICTOR_CONTEXT_HIDDEN:-64}"
  LAMBDA_TAG="${RATE_LAMBDA/./p}"

  export RATE_LAMBDA GRID_TASK_ID RANK USE_RESIDUAL USE_MORTON
  export TRANSFORM TRANSFORM_HIDDEN LAMBDA_TAG PREDICTOR_TAG
  export PARENT_PRIOR_TAG PARENT_TASK_ID
  export SCORE_MEAN_CONDITION SCORE_CHANNEL_CONTEXT SCORE_SPATIAL_CONTEXT
  export SCORE_SPATIAL_PREDICTOR SCORE_SPATIAL_HIDDEN
  export SCORE_SLICE_CHANNELS SCORE_CONTEXT_HIDDEN
}
